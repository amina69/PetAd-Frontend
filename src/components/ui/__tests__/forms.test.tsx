import { createRef } from "react";
import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it, vi } from "vitest";
import { Checkbox, Input, RadioGroup, Select, Switch, Textarea } from "../forms";

describe("form primitives", () => {
  it("associates an input label, hint, error and required state", () => {
    render(
      <Input
        id="email"
        label="Email"
        hint="We never share it."
        error="Enter a valid email"
        required
      />,
    );

    const input = screen.getByLabelText(/email/i);

    expect(input).toHaveAttribute("id", "email");
    expect(input).toBeRequired();
    expect(input).toHaveAttribute("aria-invalid", "true");
    expect(input).toHaveAttribute("aria-describedby", "email-hint email-error");
    expect(screen.getByText("We never share it.")).toHaveAttribute("id", "email-hint");
    expect(screen.getByRole("alert")).toHaveTextContent("Enter a valid email");
  });

  it("keeps caller-supplied aria-describedby ids alongside generated ones", () => {
    render(<Input id="name" label="Name" hint="As on your ID" aria-describedby="external" />);

    expect(screen.getByLabelText(/name/i)).toHaveAttribute(
      "aria-describedby",
      "name-hint external",
    );
  });

  it("forwards refs to the native input for react-hook-form", () => {
    const ref = createRef<HTMLInputElement>();
    render(<Input ref={ref} label="Nickname" name="nickname" defaultValue="Bella" />);

    expect(ref.current).toBeInstanceOf(HTMLInputElement);
    expect(ref.current).toHaveValue("Bella");
  });

  it("supports disabled state and autogenerated ids", () => {
    render(<Textarea label="Notes" disabled error="Too long" />);

    const textarea = screen.getByLabelText(/notes/i);

    expect(textarea).toBeDisabled();
    expect(textarea).toHaveAttribute("aria-invalid", "true");
    expect(textarea.getAttribute("id")).toBeTruthy();
    expect(textarea.getAttribute("aria-describedby")).toContain("-error");
  });

  it("renders select options and reports changes", async () => {
    const user = userEvent.setup();
    const onChange = vi.fn();

    render(
      <Select id="size" label="Size" placeholder="Choose a size" onChange={onChange}>
        <option value="s">Small</option>
        <option value="m">Medium</option>
      </Select>,
    );

    const select = screen.getByLabelText(/size/i);

    await user.selectOptions(select, "m");

    expect(onChange).toHaveBeenCalled();
    expect(select).toHaveValue("m");
  });

  it("renders a selectable checkbox with an associated hint", async () => {
    const user = userEvent.setup();

    render(
      <Checkbox id="terms" label="Accept terms" hint="Required to continue" />,
    );

    const checkbox = screen.getByLabelText(/accept terms/i);
    expect(checkbox).toHaveAttribute("aria-describedby", "terms-hint");

    await user.click(screen.getByText("Accept terms"));
    expect(checkbox).toBeChecked();
  });

  it("exposes a switch with switch semantics", async () => {
    const user = userEvent.setup();

    render(<Switch id="alerts" label="Email alerts" />);

    const toggle = screen.getByRole("switch", { name: /email alerts/i });
    expect(toggle).not.toBeChecked();

    await user.click(toggle);
    expect(toggle).toBeChecked();
    expect(toggle).toHaveAttribute("id", "alerts");
  });

  it("groups radios in a fieldset with a legend and reports the value", async () => {
    const user = userEvent.setup();
    const onChange = vi.fn();

    render(
      <RadioGroup
        id="contact"
        name="contact"
        label="Preferred contact"
        hint="We reply within a day"
        onChange={onChange}
        options={[
          { value: "email", label: "Email" },
          { value: "phone", label: "Phone" },
        ]}
      />,
    );

    expect(screen.getByRole("group", { name: /preferred contact/i })).toBeInTheDocument();

    const email = screen.getByRole("radio", { name: "Email" });
    expect(email).toHaveAttribute("name", "contact");
    expect(email).toHaveAttribute("aria-describedby", "contact-hint");

    await user.click(email);
    expect(email).toBeChecked();
    expect(onChange).toHaveBeenCalledWith("email");
  });
});
